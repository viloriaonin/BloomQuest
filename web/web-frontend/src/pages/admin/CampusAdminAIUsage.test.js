import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import CampusAdminAIUsage from "./CampusAdminAIUsage";

jest.mock("react-chartjs-2", () => ({
  Bar: ({ data, options }) => (
    <div
      data-testid="bar-chart"
      data-labels={JSON.stringify(data.labels)}
      data-series={JSON.stringify(data.datasets.map((dataset) => dataset.label))}
      data-chart-options={JSON.stringify(options)}
      data-background-colors={JSON.stringify(data.datasets.map((dataset) => dataset.backgroundColor))}
    />
  ),
}));

const hierarchy = {
  campuses: [{
    departments: [{
      id: 9,
      name: "Engineering",
      faculty: [
        { id: 1, name: "Alice Smith", email: "alice@example.com", program_id: 30 },
        { id: 2, name: "Bob Jones", email: "bob@example.com", program_id: 31 },
      ],
      programs: [
        { id: 30, name: "Computer Science", faculty: [{ id: 1, name: "Alice Smith" }] },
        { id: 31, name: "Civil Engineering", faculty: [{ id: 2, name: "Bob Jones" }] },
      ],
    }, {
      id: 10,
      name: "Science",
      faculty: [{ id: 3, name: "Carol Davis", email: "carol@example.com", program_id: 32 }],
      programs: [
        { id: 32, name: "Biology", faculty: [{ id: 3, name: "Carol Davis" }] },
      ],
    }, {
      id: 11,
      name: "Humanities",
      faculty: [],
      programs: [],
    }, {
      id: 12,
      name: "Arts",
      faculty: [],
      programs: [
        { id: 33, name: "Fine Arts", faculty: [] },
      ],
    }],
  }],
  faculty: [
    { id: 1, name: "Alice Smith", email: "alice@example.com" },
    { id: 2, name: "Bob Jones", email: "bob@example.com" },
  ],
};

beforeEach(() => {
  localStorage.setItem("token", "test-token");
  global.fetch = jest.fn(async (url) => ({
    ok: true,
    json: async () => {
      if (String(url).endsWith("/academic-hierarchy")) return hierarchy;
      const query = new URLSearchParams(String(url).split("?")[1] || "");
      const selectedDepartmentId = query.get("department_id");
      const isEmptyDepartment = ["11", "12"].includes(selectedDepartmentId);
      const allUsers = [
        { user_id: 1, name: "Alice Smith", email: "alice@example.com", role: "faculty", department_id: 9, program_id: 30, department: "Engineering", requests: 1, questions: 1 },
        { user_id: 2, name: "Bob Jones", email: "bob@example.com", role: "faculty", department_id: 9, program_id: 31, department: "Engineering", requests: 1, questions: 1 },
        { user_id: 3, name: "Carol Davis", email: "carol@example.com", role: "faculty", department_id: 10, program_id: 32, department: "Science", requests: 1, questions: 1 },
      ];
      const users = isEmptyDepartment ? [] : allUsers.filter((user) => (
        (!selectedDepartmentId || String(user.department_id) === selectedDepartmentId)
        && (!query.get("program_id") || String(user.program_id) === query.get("program_id"))
        && (!query.get("instructor_id") || String(user.user_id) === query.get("instructor_id"))
      ));
      const requestCount = users.reduce((sum, user) => sum + user.requests, 0);
      return {
        totals: { total_ai_requests: requestCount },
        requests_by_month: [{ month: "2026-09", requests: requestCount, questions: requestCount * 2 }],
        model_usage: [],
        requests_by_user: users,
        error_types: [],
        token_usage: { available: false },
      };
    },
  }));
});

afterEach(() => {
  delete global.fetch;
  localStorage.removeItem("token");
});

test("filters campus AI usage by department, program, and instructor", async () => {
  render(<CampusAdminAIUsage />);

  const departmentFilter = await screen.findByRole("combobox", { name: "Filter AI usage by department" });
  await waitFor(() => expect(departmentFilter).toBeEnabled());
  expect(screen.getByRole("heading", { name: "AI requests by department" })).toBeInTheDocument();
  expect(screen.getByRole("heading", { name: "Questions generated by department" })).toBeInTheDocument();
  expect(screen.getAllByTestId("bar-chart")).toHaveLength(2);
  expect(screen.queryByRole("heading", { name: "Requests by user" })).not.toBeInTheDocument();
  expect(screen.queryByText("alice@example.com")).not.toBeInTheDocument();
  expect(screen.getAllByTestId("bar-chart").map((chart) => chart.getAttribute("data-series"))).toEqual([
    JSON.stringify(["Requests"]),
    JSON.stringify(["Questions generated"]),
  ]);
  expect(screen.getAllByTestId("bar-chart").every((chart) => {
    const options = JSON.parse(chart.getAttribute("data-chart-options"));
    const colors = JSON.parse(chart.getAttribute("data-background-colors"));
    return options.indexAxis !== "y"
      && options.scales.x.ticks.minRotation > 0
      && colors[0] === "#C4485A";
  })).toBe(true);
  expect(screen.getAllByTestId("bar-chart").map((chart) => chart.getAttribute("data-labels"))).toEqual([
    JSON.stringify(["Engineering", "Science"]),
    JSON.stringify(["Engineering", "Science"]),
  ]);
  const programFilter = screen.getByRole("combobox", { name: "Filter AI usage by program" });
  const instructorFilter = screen.getByRole("combobox", { name: "Filter AI usage by instructor" });
  expect(programFilter).toBeDisabled();
  expect(instructorFilter).toBeDisabled();

  fireEvent.change(departmentFilter, { target: { value: "9" } });
  expect(programFilter).toBeEnabled();
  expect(screen.getByRole("option", { name: "Computer Science" })).toBeInTheDocument();
  await waitFor(() => {
    expect(screen.getByRole("heading", { name: "AI requests by program" })).toBeInTheDocument();
    expect(screen.getAllByTestId("bar-chart").map((chart) => chart.getAttribute("data-labels"))).toEqual([
      JSON.stringify(["Computer Science", "Civil Engineering"]),
      JSON.stringify(["Computer Science", "Civil Engineering"]),
    ]);
  });

  fireEvent.change(programFilter, { target: { value: "30" } });
  expect(instructorFilter).toBeEnabled();
  expect(screen.getByRole("option", { name: "Alice Smith" })).toBeInTheDocument();
  expect(screen.queryByRole("option", { name: "Bob Jones" })).not.toBeInTheDocument();
  await waitFor(() => {
    expect(screen.getByRole("heading", { name: "AI requests by instructor" })).toBeInTheDocument();
    expect(screen.getAllByTestId("bar-chart").map((chart) => chart.getAttribute("data-labels"))).toEqual([
      JSON.stringify(["Alice Smith"]),
      JSON.stringify(["Alice Smith"]),
    ]);
  });

  fireEvent.change(instructorFilter, { target: { value: "1" } });
  await waitFor(() => {
    const usageUrls = global.fetch.mock.calls
      .map(([url]) => String(url))
      .filter((url) => url.includes("/admin/ai-usage"));
    expect(usageUrls.some((url) => (
      url.includes("department_id=9")
      && url.includes("program_id=30")
      && url.includes("instructor_id=1")
    ))).toBe(true);
  });

  fireEvent.change(departmentFilter, { target: { value: "10" } });
  expect(programFilter).toHaveValue("");
  expect(instructorFilter).toHaveValue("");
  expect(screen.getByRole("option", { name: "Biology" })).toBeInTheDocument();
  expect(screen.queryByRole("option", { name: "Computer Science" })).not.toBeInTheDocument();
  expect(screen.getByRole("option", { name: "Carol Davis" })).toBeInTheDocument();
  expect(screen.queryByRole("option", { name: "Alice Smith" })).not.toBeInTheDocument();
  await waitFor(() => {
    expect(screen.getAllByTestId("bar-chart").map((chart) => chart.getAttribute("data-labels"))).toEqual([
      JSON.stringify(["Biology"]),
      JSON.stringify(["Biology"]),
    ]);
  });
  await waitFor(() => expect(screen.getByText("AI Requests").parentElement).toHaveTextContent("1"));
});

test("shows empty program and instructor filters and updates usage when selecting an empty department", async () => {
  render(<CampusAdminAIUsage />);

  const departmentFilter = await screen.findByRole("combobox", { name: "Filter AI usage by department" });
  await waitFor(() => expect(departmentFilter).toBeEnabled());

  fireEvent.change(departmentFilter, { target: { value: "11" } });

  const programFilter = screen.getByRole("combobox", { name: "Filter AI usage by program" });
  const instructorFilter = screen.getByRole("combobox", { name: "Filter AI usage by instructor" });
  expect(programFilter).toBeDisabled();
  expect(instructorFilter).toBeDisabled();
  expect(screen.getByRole("option", { name: "No programs available" })).toBeInTheDocument();
  expect(screen.getByRole("option", { name: "No instructors available" })).toBeInTheDocument();

  expect(await screen.findByText("No request data for this selection.")).toBeInTheDocument();
  expect(screen.getByText("No question data for this selection.")).toBeInTheDocument();
  const usageStat = screen.getByText("AI Requests").parentElement;
  expect(usageStat).toHaveTextContent("0");

  fireEvent.change(departmentFilter, { target: { value: "12" } });
  expect(screen.getByRole("option", { name: "Fine Arts" })).toBeInTheDocument();
  expect(screen.getByRole("option", { name: "No instructors available" })).toBeInTheDocument();
  expect(instructorFilter).toBeDisabled();
  expect(screen.getByText("AI Requests").parentElement).toHaveTextContent("...");
  await waitFor(() => {
    expect(global.fetch).toHaveBeenCalledWith(
      expect.stringContaining("department_id=12"),
      expect.any(Object),
    );
  });
  await waitFor(() => expect(screen.getByText("AI Requests").parentElement).toHaveTextContent("0"));
});
